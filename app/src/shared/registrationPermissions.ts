/** Retorna o nível da matriz, sem substituir a verificação de escopo. */
export function resolveRegistrationAccess(role: string, action: RegistrationAction): RegistrationAccess {
  const index = REGISTRATION_ACTIONS.indexOf(action);
  if (index < 0) return 'N';
  if (role === 'SUPER_ADMIN') return 'S';
  return rows[role]?.[action] ?? 'N';
}

/** R e P não autorizam uma operação geral; seu escopo precisa de política específica. */
export function canPerformRegistrationAction(
  role: string,
  action: RegistrationAction,
  options: { hasGrant?: boolean } = {},
): boolean {
  const access = resolveRegistrationAccess(role, action);
  return access === 'S' || (access === 'D' && options.hasGrant === true);
}
